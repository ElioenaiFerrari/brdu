//! Docker lab: generates `compose/` (keys, genesis and `docker-compose.yml` with CPU and memory limits) and
//! wraps `docker compose`. A single image (`brdu-lab:dev`) for all nodes.

use std::fs;
use std::path::Path;
use std::process::Command;

use crate::net;

const IMAGE: &str = "brdu-lab:dev";

fn docker(args: &[&str]) -> Result<bool, String> {
    Command::new("docker")
        .args(args)
        .status()
        .map(|s| s.success())
        .map_err(|e| format!("docker: {e}"))
}

fn compose(dir: &Path, args: &[&str]) -> Result<bool, String> {
    let file = dir.join("docker-compose.yml");
    let mut full = vec![
        "compose",
        "-f",
        file.to_str().unwrap_or("compose/docker-compose.yml"),
    ];
    full.extend_from_slice(args);
    docker(&full)
}

/// `compose init`: keys, genesis and the compose file.
pub fn init(
    dir: &Path,
    nodes: usize,
    spare: usize,
    cpus: &str,
    mem_mib: u64,
    min_block_ms: u64,
) -> Result<(), String> {
    let spec = net::Spec {
        chain: "brdu-lab",
        nodes,
        spare,
        issuers: 3,
        threshold: 2,
        min_window: 5,
    };
    net::init(
        dir,
        &spec,
        &|i| format!("v{i}:7000"),
        &|i| format!("127.0.0.1:{}", 7300 + i),
        &|i| format!("127.0.0.1:{}", 8200 + i),
    )?;
    let total = nodes + spare;
    let mut y = String::new();
    y.push_str("# GENERATED by `cargo dev compose init`: do not edit by hand (run `compose clean` and `compose init` again).\n");
    y.push_str("name: brdu-lab\n\nx-node: &node\n");
    y.push_str(&format!("  image: {IMAGE}\n  user: \"0:0\"\n  restart: \"no\"\n  cpus: {cpus}\n  mem_limit: {mem_mib}m\n  memswap_limit: {mem_mib}m\n  pids_limit: 256\n"));
    y.push_str("  healthcheck:\n    test: [\"CMD\", \"brdu-node\", \"health\", \"--api\", \"127.0.0.1:8080\"]\n    interval: 2s\n    timeout: 3s\n    retries: 15\n    start_period: 3s\n\nservices:\n");
    for i in 1..=total {
        y.push_str(&format!("  v{i}:\n    <<: *node\n    command:\n"));
        for a in [
            "run",
            "--genesis",
            "/lab/genesis.hex",
            "--key",
            &format!("/lab/keys/v{i}.key"),
            "--data",
            "/data",
            "--listen",
            "0.0.0.0:7000",
            "--api",
            "0.0.0.0:8080",
            "--min-block-ms",
            &min_block_ms.to_string(),
        ] {
            y.push_str(&format!("      - \"{a}\"\n"));
        }
        for j in 1..i {
            y.push_str(&format!("      - \"--peer\"\n      - \"v{j}:7000\"\n"));
        }
        y.push_str(&format!(
            "    volumes:\n      - ./genesis.hex:/lab/genesis.hex:ro\n      - ./keys/v{i}.key:/lab/keys/v{i}.key:ro\n      - data-v{i}:/data\n    ports:\n      - \"127.0.0.1:{}:8080\"\n      - \"127.0.0.1:{}:7000\"\n",
            8200 + i,
            7300 + i
        ));
    }
    // the web explorer (re-verifies every block; read-only), pointed at v1
    y.push_str("  explorer:\n    image: brdu-lab:dev\n    user: \"0:0\"\n    restart: \"no\"\n    cpus: 0.25\n    mem_limit: 128m\n    memswap_limit: 128m\n    pids_limit: 128\n    entrypoint: [\"brdu-explorer\"]\n    command: [\"--genesis\", \"/lab/genesis.hex\", \"--node\", \"v1:8080\", \"--listen\", \"0.0.0.0:8545\"]\n    volumes:\n      - ./genesis.hex:/lab/genesis.hex:ro\n    ports:\n      - \"127.0.0.1:8545:8545\"\n");
    // the wallet web server (TEST keys only): the vault lives in the `data-wallet` volume. Inside the container it listens
    // on all interfaces (`--allow-remote`, the Host check is off because of the port mapping), but the port is published
    // ONLY on the host's loopback, on 8547 (8546 is the port of the local `cargo dev wallet-web`, so both can run).
    y.push_str("  wallet:\n    image: brdu-lab:dev\n    user: \"0:0\"\n    restart: \"no\"\n    cpus: 0.25\n    mem_limit: 128m\n    memswap_limit: 128m\n    pids_limit: 128\n    entrypoint: [\"brdu-web\"]\n    command: [\"--vault\", \"/data/vault.json\", \"--node\", \"v1:8080\", \"--explorer\", \"explorer:8545\", \"--listen\", \"0.0.0.0:8546\", \"--allow-remote\"]\n    depends_on:\n      - v1\n      - explorer\n    volumes:\n      - data-wallet:/data\n    ports:\n      - \"127.0.0.1:8547:8546\"\n");
    y.push_str("\nvolumes:\n  data-wallet:\n");
    for i in 1..=total {
        y.push_str(&format!("  data-v{i}:\n"));
    }
    fs::write(dir.join("docker-compose.yml"), y).map_err(|e| e.to_string())?;
    println!(
        "lab created in {}: {nodes} validators + {spare} spare(s), {cpus} CPU and {mem_mib} MiB each; explorer at http://127.0.0.1:8545, wallet at http://127.0.0.1:8547",
        dir.display()
    );
    println!("next: cargo dev compose up   (the first time it builds the image, a few minutes)");
    Ok(())
}

/// `compose build`: builds the single image.
pub fn build() -> Result<(), String> {
    println!("building {IMAGE} (dependency cache in BuildKit)…");
    if docker(&["build", "-f", "docker/Dockerfile", "-t", IMAGE, "."])? {
        Ok(())
    } else {
        Err("docker build failed".into())
    }
}

/// `compose up`: image, containers, and waits for them to become healthy.
pub fn up(dir: &Path) -> Result<(), String> {
    // always build: with the BuildKit cache an unchanged tree takes seconds, and a stale image (without a newer binary)
    // would fail in confusing ways
    build()?;
    if !compose(dir, &["up", "-d", "--wait", "--wait-timeout", "90"])? {
        return Err("docker compose up failed (see `cargo dev compose logs`)".into());
    }
    println!("up. Query with: cargo dev --dir {} status", dir.display());
    println!(
        "  explorer  http://127.0.0.1:8545\n  wallet    http://127.0.0.1:8547   (create or import a wallet there; fund it with `cargo dev fund ADDRESS 1000 --dir {}`)",
        dir.display()
    );
    Ok(())
}

/// The remaining commands.
pub fn run(dir: &Path, sub: &str, rest: &[String]) -> Result<(), String> {
    let svc = |i: &str| format!("v{i}");
    let ok = match sub {
        "build" => return build(),
        "up" => return up(dir),
        "down" => compose(dir, &["down"])?,
        "ps" => compose(dir, &["ps"])?,
        "logs" => {
            let mut a = vec!["logs", "--tail", "60"];
            let s = rest.first().map(|i| svc(i));
            if let Some(s) = &s {
                a.push(s);
            }
            compose(dir, &a)?
        }
        "pause" | "unpause" | "kill" | "start" | "stop" | "restart" => {
            let i = rest
                .first()
                .ok_or_else(|| format!("compose {sub} NODE_NUMBER"))?;
            compose(dir, &[sub, &svc(i)])?
        }
        "stats" => docker(&["stats", "--no-stream"])?,
        "clean" => {
            // stops ONLY this lab (project brdu-lab, with its volumes) and deletes the generated files
            let _ = compose(dir, &["down", "--volumes", "--remove-orphans"]);
            for sub in ["keys", "wallets"] {
                let _ = fs::remove_dir_all(dir.join(sub));
            }
            for f in ["devnet.json", "genesis.hex", "docker-compose.yml"] {
                let _ = fs::remove_file(dir.join(f));
            }
            let _ = fs::remove_dir(dir);
            println!(
                "lab in {} deleted (image {IMAGE} stays; `docker rmi {IMAGE}` removes it)",
                dir.display()
            );
            true
        }
        other => {
            return Err(format!(
                "compose {other}: use init | build | up | down | ps | logs [N] | pause N | unpause N | kill N | start N | stop N | restart N | stats | clean"
            ));
        }
    };
    if ok {
        Ok(())
    } else {
        Err("docker returned an error".into())
    }
}
