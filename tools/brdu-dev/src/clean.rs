//! `cargo dev clean-all`: removes EVERYTHING the BRDU test environments leave on disk, because they add up (the
//! build folders alone reach gigabytes). Without `--yes` it only LISTS what it would remove, with sizes.
//!
//! Always (with `--yes`): the Docker lab of the project `brdu-lab` (containers and ITS volumes only, found by the
//! compose project label: volumes of other projects are never touched), the local processes, and the generated
//! folders `net/`, `compose/`, `dev/` and `testnet/` (only what `init` creates inside them: keys, wallets, data, logs,
//! genesis and pids; a file of yours in there stays).
//! Optional: `--tmp` (the `brdu-cli-*` folders that tests leave in the system temp folder), `--image` (the Docker image
//! `brdu-lab:dev`) and `--cargo` (`cargo clean` of the workspace and of the Tauri app).

use std::fs;
use std::path::{Path, PathBuf};
use std::process::Command;

/// What to clean.
#[derive(Debug, Clone, Default)]
pub struct Options {
    /// Really delete (otherwise only list).
    pub yes: bool,
    /// Also the test folders left in the system temp folder.
    pub tmp: bool,
    /// Also the Docker image `brdu-lab:dev`.
    pub image: bool,
    /// Also `cargo clean` (workspace and Tauri app).
    pub cargo: bool,
    /// Whether to talk to Docker at all (tests turn it off).
    pub docker: bool,
}

/// Folders generated by the dev tools, relative to the repository root.
pub const GENERATED: [&str; 4] = ["net", "compose", "dev", "testnet"];
const SUBDIRS: [&str; 6] = ["keys", "wallets", "wallet", "data", "logs", "compose-data"];
const FILES: [&str; 6] = [
    "devnet.json",
    "genesis.hex",
    "pids",
    "explorer.pid",
    "wallet-web.pid",
    "docker-compose.yml",
];
/// The Docker compose project of the lab.
pub const PROJECT: &str = "brdu-lab";

/// Total size in bytes of a file or folder (0 if it does not exist). Symbolic links are not followed.
#[must_use]
pub fn size_of(p: &Path) -> u64 {
    let Ok(meta) = fs::symlink_metadata(p) else {
        return 0;
    };
    if meta.is_dir() {
        fs::read_dir(p).map_or(0, |it| it.flatten().map(|e| size_of(&e.path())).sum())
    } else {
        meta.len()
    }
}

/// `12.3 MiB`, `4.5 GiB`…
#[must_use]
pub fn human(bytes: u64) -> String {
    let units = ["B", "KiB", "MiB", "GiB", "TiB"];
    let mut v = bytes as f64;
    let mut i = 0;
    while v >= 1024.0 && i + 1 < units.len() {
        v /= 1024.0;
        i += 1;
    }
    if i == 0 {
        format!("{bytes} B")
    } else {
        format!("{v:.1} {}", units[i])
    }
}

/// What `init` creates inside a generated folder (and only that).
fn generated_paths(dir: &Path) -> Vec<PathBuf> {
    let mut v: Vec<PathBuf> = SUBDIRS.iter().map(|s| dir.join(s)).collect();
    v.extend(FILES.iter().map(|f| dir.join(f)));
    v.into_iter().filter(|p| p.exists()).collect()
}

/// The test folders that tests leave in `tmp` (names `brdu-cli-…`).
#[must_use]
pub fn temp_leftovers(tmp: &Path) -> Vec<PathBuf> {
    fs::read_dir(tmp)
        .map(|it| {
            it.flatten()
                .map(|e| e.path())
                .filter(|p| {
                    p.is_dir()
                        && p.file_name()
                            .is_some_and(|n| n.to_string_lossy().starts_with("brdu-cli-"))
                })
                .collect()
        })
        .unwrap_or_default()
}

fn docker_ok(args: &[&str]) -> Option<String> {
    let o = Command::new("docker").args(args).output().ok()?;
    o.status
        .success()
        .then(|| String::from_utf8_lossy(&o.stdout).to_string())
}

/// Docker volumes of the lab project, by its compose label (never by name pattern).
fn lab_volumes() -> Vec<String> {
    docker_ok(&[
        "volume",
        "ls",
        "-q",
        "--filter",
        &format!("label=com.docker.compose.project={PROJECT}"),
    ])
    .map(|s| {
        s.lines()
            .map(str::to_string)
            .filter(|l| !l.is_empty())
            .collect()
    })
    .unwrap_or_default()
}

fn lab_containers() -> Vec<String> {
    docker_ok(&[
        "ps",
        "-aq",
        "--filter",
        &format!("label=com.docker.compose.project={PROJECT}"),
    ])
    .map(|s| {
        s.lines()
            .map(str::to_string)
            .filter(|l| !l.is_empty())
            .collect()
    })
    .unwrap_or_default()
}

fn remove_path(p: &Path) {
    if p.is_dir() {
        let _ = fs::remove_dir_all(p);
    } else {
        let _ = fs::remove_file(p);
    }
}

/// Runs the cleanup relative to `root` (the repository). `stop` stops the local processes of a folder (given by the
/// caller because it lives in the CLI); `tmp` is the system temp folder.
pub fn run(root: &Path, tmp: &Path, o: &Options, stop: &dyn Fn(&Path)) -> Result<(), String> {
    let verb = if o.yes { "removing" } else { "would remove" };
    let mut total = 0u64;
    let mut line = |what: &str, bytes: u64| {
        total += bytes;
        println!("  {verb} {what}  ({})", human(bytes));
    };

    if o.docker {
        let (c, v) = (lab_containers(), lab_volumes());
        if !c.is_empty() || !v.is_empty() {
            line(
                &format!(
                    "Docker lab `{PROJECT}`: {} container(s), {} volume(s)",
                    c.len(),
                    v.len()
                ),
                0,
            );
        }
    }
    let mut paths: Vec<PathBuf> = Vec::new();
    for g in GENERATED {
        paths.extend(generated_paths(&root.join(g)));
    }
    if o.tmp {
        paths.extend(temp_leftovers(tmp));
    }
    for p in &paths {
        line(&p.display().to_string(), size_of(p));
    }
    let targets = [
        root.join("target"),
        root.join("apps/wallet/src-tauri/target"),
    ];
    if o.cargo {
        for t in &targets {
            if t.exists() {
                line(&format!("{} (cargo clean)", t.display()), size_of(t));
            }
        }
    }
    if o.image && o.docker {
        line("Docker image brdu-lab:dev", 0);
    }
    println!(
        "{} {}",
        if o.yes {
            "freed about"
        } else {
            "total that would be freed:"
        },
        human(total)
    );
    if !o.yes {
        println!(
            "nothing was deleted: add --yes to do it (and --tmp, --image, --cargo for the optional parts)"
        );
        return Ok(());
    }

    for g in GENERATED {
        stop(&root.join(g));
    }
    if o.docker {
        // containers and volumes of the lab project only
        let c = lab_containers();
        if !c.is_empty() {
            let mut a = vec!["rm", "-f", "-v"];
            a.extend(c.iter().map(String::as_str));
            let _ = docker_ok(&a);
        }
        let v = lab_volumes();
        if !v.is_empty() {
            let mut a = vec!["volume", "rm", "-f"];
            a.extend(v.iter().map(String::as_str));
            let _ = docker_ok(&a);
        }
        let _ = docker_ok(&["network", "rm", &format!("{PROJECT}_default")]);
    }
    for p in &paths {
        remove_path(p);
    }
    for g in GENERATED {
        let _ = fs::remove_dir(root.join(g)); // only if it is empty now
    }
    if o.image && o.docker {
        let _ = docker_ok(&["rmi", "brdu-lab:dev"]);
    }
    if o.cargo {
        let _ = Command::new("cargo")
            .args(["clean"])
            .current_dir(root)
            .status();
        let tauri = root.join("apps/wallet/src-tauri/Cargo.toml");
        if tauri.exists() {
            let _ = Command::new("cargo")
                .args(["clean", "--manifest-path"])
                .arg(&tauri)
                .status();
        }
    }
    println!("done");
    Ok(())
}

#[cfg(test)]
#[allow(clippy::unwrap_used, clippy::expect_used, clippy::panic)]
mod tests {
    use super::*;

    fn scratch(name: &str) -> PathBuf {
        let d = std::env::temp_dir().join(format!("brdu-clean-test-{}-{name}", std::process::id()));
        let _ = fs::remove_dir_all(&d);
        fs::create_dir_all(&d).unwrap();
        d
    }

    fn world(root: &Path) {
        for g in ["net", "compose"] {
            fs::create_dir_all(root.join(g).join("keys")).unwrap();
            fs::create_dir_all(root.join(g).join("data/v1")).unwrap();
            fs::create_dir_all(root.join(g).join("wallet")).unwrap();
            fs::write(root.join(g).join("keys/v1.key"), vec![1u8; 100]).unwrap();
            fs::write(root.join(g).join("data/v1/blocks.log"), vec![2u8; 5_000]).unwrap();
            fs::write(root.join(g).join("wallet/vault.json"), b"{}").unwrap();
            fs::write(root.join(g).join("devnet.json"), b"{}").unwrap();
        }
        fs::write(root.join("compose/docker-compose.yml"), b"x").unwrap();
    }

    fn opts(yes: bool) -> Options {
        Options {
            yes,
            docker: false,
            ..Options::default()
        }
    }

    #[test]
    fn without_yes_nothing_is_deleted() {
        let root = scratch("dry");
        world(&root);
        run(&root, &root, &opts(false), &|_| {}).unwrap();
        assert!(
            root.join("net/keys/v1.key").exists()
                && root.join("compose/data/v1/blocks.log").exists()
        );
        let _ = fs::remove_dir_all(&root);
    }

    #[test]
    fn with_yes_it_removes_what_init_creates_and_keeps_your_own_files() {
        let root = scratch("yes");
        world(&root);
        fs::write(root.join("net/my-notes.txt"), b"keep me").unwrap();
        fs::write(root.join("README.md"), b"repo").unwrap();
        fs::create_dir_all(root.join("crates")).unwrap();
        let stopped = std::cell::RefCell::new(Vec::new());
        run(&root, &root, &opts(true), &|d| {
            stopped.borrow_mut().push(d.to_path_buf())
        })
        .unwrap();
        assert!(
            !root.join("net/keys").exists()
                && !root.join("net/wallet").exists()
                && !root.join("net/data").exists()
        );
        assert!(
            !root.join("compose").exists(),
            "an emptied generated folder disappears"
        );
        assert!(
            root.join("net/my-notes.txt").exists(),
            "files that init does not create stay (and so does their folder)"
        );
        assert!(
            root.join("README.md").exists() && root.join("crates").exists(),
            "the rest of the repository is never touched"
        );
        assert_eq!(
            stopped.borrow().len(),
            GENERATED.len(),
            "local processes of every folder are stopped first"
        );
        let _ = fs::remove_dir_all(&root);
    }

    #[test]
    fn tmp_removes_only_the_test_folders_with_the_brdu_prefix() {
        let root = scratch("tmp-root");
        let tmp = scratch("tmp-dir");
        fs::create_dir_all(tmp.join("brdu-cli-1-cred")).unwrap();
        fs::create_dir_all(tmp.join("other-project")).unwrap();
        fs::write(tmp.join("brdu-cli-file"), b"a file, not a folder").unwrap();
        let o = Options {
            tmp: true,
            ..opts(true)
        };
        run(&root, &tmp, &o, &|_| {}).unwrap();
        assert!(!tmp.join("brdu-cli-1-cred").exists());
        assert!(tmp.join("other-project").exists() && tmp.join("brdu-cli-file").exists());
        let _ = fs::remove_dir_all(&root);
        let _ = fs::remove_dir_all(&tmp);
    }

    #[test]
    fn sizes_are_counted_and_formatted() {
        let root = scratch("size");
        fs::create_dir_all(root.join("a")).unwrap();
        fs::write(root.join("a/x"), vec![0u8; 3_000]).unwrap();
        fs::write(root.join("y"), vec![0u8; 1_000]).unwrap();
        assert_eq!(size_of(&root), 4_000);
        assert_eq!(size_of(&root.join("missing")), 0);
        assert_eq!(human(512), "512 B");
        assert_eq!(human(2_048), "2.0 KiB");
        assert_eq!(human(5 * 1024 * 1024 * 1024), "5.0 GiB");
        let _ = fs::remove_dir_all(&root);
    }
}
